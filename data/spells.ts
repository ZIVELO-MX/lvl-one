export function spellsForClass(classId: string, maxLevel = 9): Spell[] {
  return SPELLS.filter((spell) => spell.level <= maxLevel && spell.classes.includes(classId));
}

export function spellsByLevel(level: Spell["level"]): Spell[] {
  return SPELLS.filter((spell) => spell.level === level);
}
